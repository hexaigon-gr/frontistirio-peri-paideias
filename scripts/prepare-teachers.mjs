/**
 * Turns the teacher portraits in `photos/` into the team assets.
 *
 *   node scripts/prepare-teachers.mjs
 *
 * The portraits arrive from different phones at different sizes and colour
 * temperatures, so they are cropped to one ratio and given the same light grade.
 * The grade is deliberately gentle: these are photographs of real people, and a
 * heavy tint to "match the brand" makes a face look ill.
 *
 * Cropping uses sharp's attention strategy, which favours the region with the
 * most detail and lands on the face. Every output is checked by eye before it
 * ships, because an automatic crop that clips a chin is worse than no crop.
 */
import { writeFile } from "node:fs/promises";

import sharp from "sharp";

const OUT_DIR = "public/images/team";
const MAP_FILE = "lib/general/team-blur.ts";
const WIDTH = 900;
const HEIGHT = 1125;
const BLUR_EDGE = 16;

/**
 * Explicit, so a new file dropped into `photos/` never silently reshuffles the map.
 *
 * `crop` is an optional region taken before the resize, in pixels of the source.
 * Two of these are already framed as portraits; the third is a wide shot of a
 * teacher at a whiteboard, and `sharp.strategy.attention` keeps the formulas as
 * happily as it keeps the face, which leaves his head a third the size of the
 * others in the same grid. The board is worth keeping, so the region is chosen
 * by hand rather than the photo being cropped to a headshot.
 */
const SOURCES = [
  { file: "photos/Καλλεργη Γιαννα.jpg", slug: "kallergi" },
  { file: "photos/Μανθαιάκη Μαρία.png", slug: "manthaiaki" },
  {
    file: "photos/Τριαματακης κωστας.jpg",
    slug: "triamatakis",
    crop: { left: 480, top: 330, width: 720, height: 900 },
  },
];

const run = async () => {
  const entries = [];

  for (const { file, slug, crop } of SOURCES) {
    const target = `${OUT_DIR}/${slug}.webp`;

    const pipeline = sharp(file).rotate();
    if (crop) pipeline.extract(crop);

    await pipeline
      // Flatten first: one portrait arrived as a PNG with an alpha channel, and
      // WebP would carry the transparency into the tile.
      .flatten({ background: "#ffffff" })
      .resize({ width: WIDTH, height: HEIGHT, fit: "cover", position: sharp.strategy.attention })
      .modulate({ saturation: 0.9, brightness: 1.02 })
      .linear(1.06, -6)
      .webp({ quality: 84 })
      .toFile(target);

    const { width, height } = await sharp(target).metadata();
    const blur = await sharp(target)
      .resize({ width: BLUR_EDGE, height: BLUR_EDGE, fit: "inside" })
      .jpeg({ quality: 45 })
      .toBuffer();

    entries.push({
      slug,
      width,
      height,
      blurDataURL: `data:image/jpeg;base64,${blur.toString("base64")}`,
    });
    console.log(`${file} -> ${slug}.webp ${width}x${height}`);
  }

  const body = entries
    .map(
      (entry) =>
        `  "${entry.slug}": {\n` +
        `    src: "/images/team/${entry.slug}.webp",\n` +
        `    width: ${entry.width},\n` +
        `    height: ${entry.height},\n` +
        `    blurDataURL:\n      "${entry.blurDataURL}",\n` +
        `  },`,
    )
    .join("\n");

  await writeFile(
    MAP_FILE,
    `/**\n` +
      ` * GENERATED by scripts/prepare-teachers.mjs. Do not edit by hand.\n` +
      ` *\n` +
      ` * Only teachers who sent a portrait appear here. The team section falls back\n` +
      ` * to the initial in a chalk frame for anyone missing.\n` +
      ` */\n` +
      `import type { GalleryImage } from "@/lib/general/gallery-blur";\n\n` +
      `export const TEAM_PHOTOS: Record<string, GalleryImage> = {\n${body}\n};\n`,
    "utf8",
  );

  console.log(`\nWrote ${MAP_FILE} with ${entries.length} entries`);
};

run().catch((error) => {
  console.error(error.message);
  process.exit(1);
});
